_ENV_DECLARATION = re.compile(r"^\s*#?\s*([A-Z][A-Z0-9_]*)=(.*)$")
_SECRET_NAME = re.compile(r"(?:API_KEY|ENCRYPTION_KEY|PASSWORD|SECRET|TOKEN)$")
