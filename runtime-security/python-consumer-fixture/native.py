import json
import os
from pathlib import Path
import platform
import shutil
import subprocess
import sys
import urllib.request

from integrity import HEX64, pins, read_archive, sha256, strict_json, validate_members

BASE = "ubuntu:26.04@sha256:f144425ff09be612d6d9ad965196e9cdc23dae1f42110a8a11a3e9a8198759f7"
BASE_KEYRING_SHA256 = "80a36b0a6de2f69f49d2df75ef473ccde121e9e190b9ea01d20a4f63778d5c31"
MODULE_PATHS = {
    "src.education.remediation.pdf_remediator": "src/education/remediation/pdf_remediator.py",
    "src.education.handwritten_math_suitability": "src/education/handwritten_math_suitability.py",
}


def digest(path: Path) -> str:
    return sha256(path.read_bytes())


def command(args: list[str], *, log: Path | None = None, timeout: int = 1200) -> str:
    if log is None:
        result = subprocess.run(
            args, check=True, capture_output=True, text=True, timeout=timeout
        )
        return result.stdout.strip()
    with log.open("w") as output:
        result = subprocess.run(
            args, stdout=output, stderr=subprocess.STDOUT, text=True, timeout=timeout
        )
    if result.returncode:
        raise RuntimeError("private command failed; see retained stage log")
    return ""


def check_scratch(path: Path) -> None:
    if not path.is_absolute() or path.exists() or path.resolve() != path:
        raise ValueError("scratch must be a new canonical absolute path")
    parent = path.parent.resolve(strict=True)
    if (
        parent != path.parent
        or not parent.is_dir()
        or parent.stat().st_uid != os.getuid()
    ):
        raise ValueError("scratch parent must be canonical and owned by operator")


def source_to_disk(root: Path, members: dict[str, bytes]) -> None:
    root.mkdir(mode=0o700)
    for name, data in members.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)


def capture_input(root: Path, context: Path, arch: str) -> None:
    bundle = root / "input"
    bundle.mkdir(mode=0o700)
    for name in ("apt-lists", "apt-debs", "wheels", "keyring"):
        (bundle / name).mkdir()
    # This script is generated by the independently authenticated bootstrap.
    # Only the public Ubuntu APT and PyPI endpoints are used.
    inside = r"""set -euo pipefail
test "$(sha256sum /usr/share/keyrings/ubuntu-archive-keyring.gpg | cut -d ' ' -f1)" = "$EXPECTED_KEYRING_SHA256"
rm -f /etc/apt/apt.conf.d/docker-clean
printf 'Binary::apt::APT::Keep-Downloaded-Packages "true";\n' > /etc/apt/apt.conf.d/99fixture-keep
apt-get update > /bundle/apt-update.log 2>&1
apt-get install -y --download-only --no-install-recommends $(cat /context/system-packages.txt) > /bundle/apt-download.log 2>&1
apt-get install -y --no-download --no-install-recommends $(cat /context/system-packages.txt) > /bundle/apt-install.log 2>&1
cp /usr/share/keyrings/ubuntu-archive-keyring.gpg /bundle/keyring/
cp /var/lib/apt/lists/* /bundle/apt-lists/ 2>/dev/null || true
cp /var/cache/apt/archives/*.deb /bundle/apt-debs/
dpkg-query -W -f='${binary:Package}\t${Version}\t${Architecture}\n' > /bundle/installed-packages.txt
python3 -m venv /tmp/fixture-venv
/tmp/fixture-venv/bin/python -m pip download --isolated --no-cache-dir --only-binary=:all: --no-deps --index-url https://pypi.org/simple/ --dest /bundle/wheels -r /context/pins.txt pillow==13.0.0 psycopg2-binary==2.9.13 > /bundle/pip-download.log 2>&1
chown -R "$OPERATOR_UID:$OPERATOR_GID" /bundle
"""
    args = [
        "docker",
        "run",
        "--rm",
        "--pull=never",
        "--platform",
        f"linux/{arch}",
        "--network",
        "bridge",
        "--cpus",
        "4",
        "--memory",
        "8g",
        "--pids-limit",
        "512",
        "--security-opt",
        "no-new-privileges",
        "-e",
        f"EXPECTED_KEYRING_SHA256={BASE_KEYRING_SHA256}",
        "-e",
        f"OPERATOR_UID={os.getuid()}",
        "-e",
        f"OPERATOR_GID={os.getgid()}",
        "--mount",
        f"type=bind,src={context},dst=/context,readonly",
        "--mount",
        f"type=bind,src={bundle},dst=/bundle",
        "--entrypoint",
        "/bin/bash",
        BASE,
        "-c",
        inside,
    ]
    command(args, log=root / "capture-console.log", timeout=1800)
    if digest(bundle / "keyring" / "ubuntu-archive-keyring.gpg") != BASE_KEYRING_SHA256:
        raise ValueError("captured base keyring changed")


def wheel_candidates(raw: bytes) -> dict[str, str]:
    document = strict_json(raw)
    if type(document) is not dict or type(document.get("urls")) is not list:
        raise ValueError("official metadata schema")
    candidates: dict[str, str] = {}
    for item in document["urls"]:
        if type(item) is not dict or type(item.get("packagetype")) is not str:
            raise ValueError("official file metadata schema")
        if item["packagetype"] != "bdist_wheel":
            continue
        filename, digests = item.get("filename"), item.get("digests")
        if (
            type(filename) is not str
            or type(digests) is not dict
            or type(digests.get("sha256")) is not str
        ):
            raise ValueError("official wheel metadata schema")
        digest_text = digests["sha256"]
        if (
            not filename.endswith(".whl")
            or "/" in filename
            or "\\" in filename
            or not HEX64.fullmatch(digest_text)
            or filename in candidates
        ):
            raise ValueError("official wheel metadata identity")
        candidates[filename] = digest_text
    return candidates


def authenticate_pypi(
    bundle: Path, selected: dict[str, str], arch: str
) -> dict[str, object]:
    wheel_files = sorted((bundle / "wheels").glob("*.whl"))
    if len(wheel_files) != len(selected):
        raise ValueError("official wheel count differs from exact public pins")
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    metadata = {}
    owned: set[str] = set()
    for name, version in sorted(selected.items()):
        request = urllib.request.Request(
            f"https://pypi.org/pypi/{name}/{version}/json",
            headers={"Accept": "application/json"},
        )
        with opener.open(request, timeout=30) as response:
            assert response.url.startswith("https://pypi.org/pypi/")
            raw = response.read(8_000_000)
        candidates = wheel_candidates(raw)
        matches = [path for path in wheel_files if path.name in candidates]
        if len(matches) != 1 or matches[0].name in owned:
            raise ValueError("missing, extra, or duplicate official wheel")
        wheel = matches[0]
        if "musllinux" in wheel.name or (
            "linux" in wheel.name
            and ("aarch64" if arch == "amd64" else "x86_64") in wheel.name
        ):
            raise ValueError("wheel architecture differs from native host")
        published = candidates[wheel.name]
        if digest(wheel) != published:
            raise ValueError("downloaded wheel differs from official PyPI digest")
        owned.add(wheel.name)
        metadata[name] = {
            "version": version,
            "filename": wheel.name,
            "sha256": published,
            "size": wheel.stat().st_size,
            "public_metadata_response_sha256": sha256(raw),
        }
    if owned != {path.name for path in wheel_files}:
        raise ValueError("unowned downloaded wheel")
    (bundle / "pypi-metadata.json").write_text(
        json.dumps(metadata, sort_keys=True, indent=2) + "\n"
    )
    return metadata


def lock_input(bundle: Path) -> dict[str, int | str]:
    # APT logs are private diagnostics, not install inputs or exported receipts.
    for name in (
        "apt-update.log",
        "apt-download.log",
        "apt-install.log",
        "pip-download.log",
    ):
        path = bundle / name
        if path.exists():
            path.rename(bundle.parent / name)
    files = sorted(path for path in bundle.rglob("*") if path.is_file())
    if any(path.is_symlink() for path in bundle.rglob("*")):
        raise ValueError("frozen bundle symlink")
    counts = {
        name: len(list((bundle / name).glob(pattern)))
        for name, pattern in (
            ("apt-lists", "*InRelease"),
            ("apt-debs", "*.deb"),
            ("wheels", "*.whl"),
        )
    }
    if any(count <= 0 for count in counts.values()):
        raise ValueError("frozen input closure is empty")
    text = "".join(f"{digest(path)}  {path.relative_to(bundle)}\n" for path in files)
    (bundle / "input.sha256").write_text(text)
    return {
        "input_manifest_sha256": sha256(text.encode()),
        "apt_inrelease_count": counts["apt-lists"],
        "apt_deb_count": counts["apt-debs"],
        "wheel_count": counts["wheels"],
    }


def verify_input(bundle: Path) -> None:
    expected = {}
    for line in (bundle / "input.sha256").read_text().splitlines():
        digest_text, name = line.split("  ", 1)
        if name in expected or len(digest_text) != 64:
            raise ValueError("duplicate or malformed frozen input lock")
        expected[name] = digest_text
    actual = {
        str(path.relative_to(bundle)) for path in bundle.rglob("*") if path.is_file()
    }
    if actual != set(expected) | {"input.sha256"}:
        raise ValueError("frozen input inventory changed")
    for name, expected_digest in expected.items():
        path = bundle / name
        if path.is_symlink() or digest(path) != expected_digest:
            raise ValueError("frozen input bytes changed")


def validate_baseline(
    raw: bytes, expected_modules: dict[str, str], selected_count: int
) -> dict[str, object]:
    data = strict_json(raw)
    fields = {
        "passed",
        "state",
        "selected_public_pins",
        "record_entries",
        "private_library_dirs_present",
        "loaded_modules_sha256",
        "loaded_libraries",
        "apt_versions",
        "ubuntu_archive_keyring_sha256",
        "pdf_optional_ocr_import",
    }
    if (
        type(data) is not dict
        or set(data) != fields
        or data["passed"] is not True
        or data["state"] != "official-wheel-before-replacement"
    ):
        raise ValueError("baseline verifier schema or status")
    if (
        type(data["selected_public_pins"]) is not int
        or data["selected_public_pins"] != selected_count
    ):
        raise ValueError("baseline exact pin count")
    if data["private_library_dirs_present"] != ["pillow.libs", "psycopg2_binary.libs"]:
        raise ValueError("baseline private library directories")
    if (
        data["loaded_modules_sha256"] != expected_modules
        or data["ubuntu_archive_keyring_sha256"] != BASE_KEYRING_SHA256
    ):
        raise ValueError("baseline source or keyring identity")
    records = data["record_entries"]
    if (
        type(records) is not dict
        or set(records) != {"pillow", "psycopg2-binary"}
        or any(type(value) is not int or value <= 10 for value in records.values())
    ):
        raise ValueError("baseline installed RECORD evidence")
    libraries = data["loaded_libraries"]
    if type(libraries) is not dict or set(libraries) != {"pillow", "psycopg2"}:
        raise ValueError("baseline loader schema")
    for links in libraries.values():
        if (
            type(links) is not dict
            or not links
            or not any(
                type(value) is dict and value.get("location") == "wheel-private"
                for value in links.values()
            )
        ):
            raise ValueError("baseline private loader linkage")
        if any(
            type(value) is not dict
            or set(value) != {"location", "sha256"}
            or value["location"] not in {"wheel-private", "system"}
            or type(value["sha256"]) is not str
            or not HEX64.fullmatch(value["sha256"])
            for value in links.values()
        ):
            raise ValueError("baseline loader identity")
    versions = data["apt_versions"]
    if (
        type(versions) is not dict
        or set(versions)
        != {
            "libpq5",
            "libssl3t64",
            "libtiff6",
            "libavif16",
            "libraqm0",
            "fonts-urw-base35",
        }
        or any(
            type(value) is not str
            or not value
            or any(character.isspace() for character in value)
            for value in versions.values()
        )
    ):
        raise ValueError("baseline system package identity")
    if type(data["pdf_optional_ocr_import"]) is not bool:
        raise ValueError("baseline optional-import status")
    return data


def build(
    root: Path,
    context: Path,
    bundle: Path,
    arch: str,
    expected_modules: dict[str, str],
    selected_count: int,
) -> tuple[str, dict[str, object]]:
    verify_input(bundle)
    shutil.copytree(bundle, context / "frozen")
    image_file = root / "image-id.txt"
    command(
        [
            "docker",
            "build",
            "--no-cache",
            "--pull=false",
            "--platform",
            f"linux/{arch}",
            "--network",
            "none",
            "-f",
            str(context / "Dockerfile"),
            "--iidfile",
            str(image_file),
            str(context),
        ],
        log=root / "build.log",
        timeout=2400,
    )
    image = image_file.read_text().strip()
    if (
        not image.startswith("sha256:")
        or command(
            ["docker", "image", "inspect", "--format", "{{.Architecture}}", image]
        )
        != arch
    ):
        raise ValueError("built image identity or architecture invalid")
    result = command(
        [
            "docker",
            "run",
            "--rm",
            "--pull=never",
            "--platform",
            f"linux/{arch}",
            "--network",
            "none",
            "--read-only",
            "--user",
            "1000:1000",
            "--cap-drop",
            "ALL",
            "--security-opt",
            "no-new-privileges",
            "--cpus",
            "2",
            "--memory",
            "4g",
            "--pids-limit",
            "256",
            "--tmpfs",
            "/tmp:rw,nosuid,nodev,size=128m",
            "--entrypoint",
            "/opt/venv/bin/python",
            image,
            "/fixture/verify.py",
        ],
        timeout=120,
    )
    data = validate_baseline(result.encode(), expected_modules, selected_count)
    return image, data


def main() -> None:
    parser = argparse.ArgumentParser()
    for name in ("scratch", "archive"):
        parser.add_argument("--" + name, type=Path, required=True)
    for name in ("archive-sha256", "origin", "commit", "requirements-blob", "src-tree"):
        parser.add_argument("--" + name, required=True)
    args = parser.parse_args()
    if os.getuid() == 0 or platform.system() != "Linux":
        raise ValueError("nonroot native Linux required")
    arch = {"aarch64": "arm64", "x86_64": "amd64"}.get(platform.machine())
    if arch is None or command(
        ["docker", "info", "--format", "{{.Architecture}}"]
    ) not in ({"arm64", "aarch64"} if arch == "arm64" else {"amd64", "x86_64"}):
        raise ValueError("native Docker daemon architecture required")
    if (
        command(["docker", "image", "inspect", "--format", "{{.Architecture}}", BASE])
        != arch
    ):
        raise ValueError("pinned base architecture unavailable")
    base_id = command(["docker", "image", "inspect", "--format", "{{.Id}}", BASE])
    check_scratch(args.scratch)
    archive = args.archive.absolute()
    if archive.is_symlink() or not archive.is_file() or archive.resolve() != archive:
        raise ValueError("context archive path invalid")
    members = read_archive(archive, args.archive_sha256)
    source = validate_members(
        members,
        origin=args.origin,
        commit=args.commit,
        requirements_blob=args.requirements_blob,
        src_tree=args.src_tree,
    )
    root = args.scratch
    root.mkdir(mode=0o700)
    (root / "context.tar").write_bytes(archive.read_bytes())
    context = root / "context"
    source_to_disk(context, members)
    stage = "capture"
    try:
        capture_input(root, context, arch)
        selected = pins(members["pins.txt"])
        selected.update({"pillow": "13.0.0", "psycopg2-binary": "2.9.13"})
        metadata = authenticate_pypi(root / "input", selected, arch)
        frozen = lock_input(root / "input")
        stage = "offline-build"
        inventory = strict_json(members["source-inventory.json"])
        hashes = {item["path"]: item["sha256"] for item in inventory}
        expected_modules = {
            module: hashes[path] for module, path in MODULE_PATHS.items()
        }
        image, baseline = build(
            root, context, root / "input", arch, expected_modules, len(selected)
        )
        receipt = {
            "status": "official_wheel_baseline_pass",
            "architecture": arch,
            "base_manifest": BASE,
            "base_image_id": base_id,
            "image_id": image,
            "source": source,
            "commit": args.commit,
            "origin": args.origin,
            "archive_sha256": args.archive_sha256,
            "frozen_input": frozen,
            "official_component_wheels": {
                name: metadata[name] for name in ("pillow", "psycopg2-binary")
            },
            "baseline": baseline,
        }
        (root / "receipt.json").write_text(
            json.dumps(receipt, sort_keys=True, indent=2) + "\n"
        )
        print(
            json.dumps(
                {
                    "status": receipt["status"],
                    "architecture": arch,
                    "image_id": image,
                    "archive_sha256": args.archive_sha256,
                    "input_manifest_sha256": frozen["input_manifest_sha256"],
                    "baseline_private_dirs": baseline["private_library_dirs_present"],
                },
                sort_keys=True,
            )
        )
    except Exception:
        (root / "failure-stage.txt").write_text(stage + "\n")
        raise


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print(f"fixture_failed: {type(error).__name__}: {error}", file=sys.stderr)
        raise SystemExit(1)
